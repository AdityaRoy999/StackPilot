def prepare(root, archetype):
    root = Path(root).resolve()
    from repository_plan import normalize, prepare_components
    original=json.loads((root/'stackpilot.json').read_text()) if (root/'stackpilot.json').is_file() else {}
    normalized, graph=normalize(root,original)
    if graph:
        record=root/'.stackpilot-repository-plan.json'
        if record.is_symlink():raise ValueError('Reserved repository plan cannot be a symlink')
        record.write_text(json.dumps(graph,indent=2))
        try:
            component_contracts=prepare_components(root,normalized,graph,prepare)
        finally:
            # Keep the authoritative graph and acceptance inputs across retries.
            # A single component at the root temporarily uses v1 for recursion.
            (root/'stackpilot.json').write_text(json.dumps(original,indent=2))
    contract = plan(root, archetype)
    if graph:
        contract['repository_plan']=graph
        contract['component_contracts']=component_contracts
        if not contract['port']:
            contract['port']=component_contracts[graph['primary_component']]['port']
    assets = root/'.stackpilot-runtime'
    if assets.is_symlink():
        raise ValueError('Reserved runtime asset directory must not be a symlink')
    assets.mkdir(exist_ok=True)
    sources = {source.name:source for source in ASSETS.iterdir()
               if source.is_file() and source.suffix in {'.py','.js','.cjs'}}
    sources['repository_discovery.py'] = Path(analyze.__code__.co_filename)
    from repository_toolchains import discover as discover_toolchains
    sources['repository_toolchains.py'] = Path(discover_toolchains.__code__.co_filename)
    def copy_asset(source):
        target = assets/source.name
        if target.is_symlink():
            raise ValueError('Reserved runtime asset must not be a symlink')
        shutil.copyfile(source,target)
    # Independent helper writes can have high latency on mounted workspaces.
    # Keep the full helper set and finish every bounded copy before admission.
    with ThreadPoolExecutor(max_workers=min(8,len(sources))) as copies:
        list(copies.map(copy_asset,sources.values()))
    dockerfile = root/'Dockerfile'
    if dockerfile.is_symlink():
        raise ValueError('Dockerfile must not be a symlink')
    if dockerfile.is_file():
        contents = dockerfile.read_text()
        legacy_helper = '.stackpilot-runtime/node_tasks.js'
        if legacy_helper in contents:
            # Repair workspaces can retain a Dockerfile generated by a prior
            # StackPilot release. The helper is now CommonJS .cjs so it also
            # runs inside repositories with "type": "module".
            dockerfile.write_text(contents.replace(legacy_helper,'.stackpilot-runtime/node_tasks.cjs'))
    if (root/'.stackpilot-plan.json').is_symlink():raise ValueError('Reserved plan must not be a symlink')
    (root/'.stackpilot-plan.json').write_text(json.dumps(contract,indent=2))
    if contract['sandbox']['status'] != 'ready':
        raise ValueError('Required sandbox is unavailable; provisioning request: '+json.dumps(contract['sandbox']['provisioning']))
    if contract['workload']=='android':
        from sdk_prepare import packages
        if (root/'.stackpilot-sdk.json').is_symlink():raise ValueError('Reserved SDK plan must not be a symlink')
        (root/'.stackpilot-sdk.json').write_text(json.dumps(packages(root)))
    if not (root/'Dockerfile').exists():
        from portable_build import dockerfile
        config=json.loads((root/'stackpilot.json').read_text()) if (root/'stackpilot.json').is_file() else {}
        template = dockerfile(config,contract['workload'])
        if template is None:
            template = android_dockerfile() if contract['workload']=='android' else desktop_dockerfile() if archetype=='desktop_compose_gui' else None
        if template is None:
            from linux_recipes import dockerfile as linux_dockerfile
            template = linux_dockerfile(root,contract['repository_discovery'],config,contract)
        if template is None and contract['workload'] in {'cli','job'} and contract.get('entrypoint') and contract['entrypoint'][0].split('/')[-1] in {'python','python3'}:
            template = python_console_dockerfile()
        if template is None and contract['workload'] in {'cli','job'} and contract.get('entrypoint') and contract['entrypoint'][0]=='node' and (root/'package.json').is_file():
            template = node_console_dockerfile()
        if template:
            (root/'Dockerfile').write_text(template)
    return contract


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('root',type=Path)
    parser.add_argument('--archetype',default='standard_web')
    args = parser.parse_args()
    print(json.dumps(prepare(args.root,args.archetype)))
