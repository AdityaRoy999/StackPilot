# 4. SupervisorAgent
# ---------------------------------------------------------------------------

class SupervisorAgent:
    """
    SupervisorAgent:
    - Orchestrates the subagent lifecycle
    - Manages shared SwarmContext state
    - Enforces human-in-the-loop tool permissions
    - Synthesizes the unified final multi-agent report
    """

    ROLE: str = "Supervisor"
    ICON: str = "👑"

    HIGH_RISK_TOOLS: Set[str] = {
        "terminal_run_command",
        "workspace_trigger_rebuild",
        "deploy_project",
        "workspace_write_file",
        "workspace_edit_file",
        "scale_deployment",
        "repair_deployment",
        "trigger_build",
    }

    def __init__(
        self,
        goal: str = "",
        project_id: Optional[str] = None,
        deployment_id: Optional[str] = None,
        user_id: Optional[str] = None,
    ):
        self.context = SwarmContext(
            goal=goal,
            project_id=project_id,
            deployment_id=deployment_id,
            user_id=user_id,
        )
        self.architect = ArchitectAgent()
        self.coder = CoderAgent()
        self.verifier = VerifierAgent()

    def record_lifecycle_event(self, event: str) -> None:
        """Append subagent lifecycle transition to context."""
        self.context.lifecycle_events.append(f"[{time.strftime('%H:%M:%S')}] {event}")

    def requires_permission(
        self,
        tool_name: str,
        tool_args: Dict[str, Any],
        runtime_permissions: Dict[str, Any],
        agent_access_mode: Optional[str] = None,
    ) -> bool:
        """
        Determine whether executing tool_name requires human-in-the-loop authorization.
        Enforces policy:
        - If agent_access_mode == 'ask' and tool is high-risk mutating tool
        - If tool_name == 'terminal_run_command' and remote_terminal == 'ask'
        - If require_confirmation flag is explicitly set
        """
        mode = agent_access_mode or runtime_permissions.get("agent_access_mode") or "ask"
        remote_term = runtime_permissions.get("remote_terminal", "ask")
        require_confirm = runtime_permissions.get("require_confirmation", mode != "full_access")

        # Remote terminal specific check
        if tool_name == "terminal_run_command" and remote_term == "ask":
            return True

        # Mutating tool check
        if tool_name in self.HIGH_RISK_TOOLS:
            if mode == "ask":
                return True
            if require_confirm and mode != "full_access":
                return True

        return False

    def is_confirmation_approved(
        self,
        tool_name: str,
        tool_args: Dict[str, Any],
        request_data: Any,
        history: Optional[List[Dict[str, str]]] = None,
    ) -> bool:
        """Consume an approval signed for this exact user, session and action.

        Narration, history and model-supplied boolean flags are never approval.
        The active main loop uses the same approval broker directly.
        """
        from .agent_runtime.approval import consume
        return consume(getattr(request_data, "approval_token", None), request_data, tool_name, tool_args)

    def create_permission_request(
        self,
        tool_name: str,
        tool_args: Dict[str, Any],
    ) -> Dict[str, Any]:
        """Generate structured permission request payload for frontend interactive card."""
        cmd = tool_args.get("command") if tool_name == "terminal_run_command" else None
        desc = (
            f"Execute terminal command `{cmd}`"
            if cmd else
            f"Run high-risk tool `{tool_name}`"
        )
        return {
            "type": "permission_request",
            "tool_name": tool_name,
            "arguments": tool_args,
            "risk_level": "high",
            "description": desc,
            "command": cmd,
        }

    def synthesize_report(self, custom_summary: Optional[str] = None) -> str:
        """Synthesize unified final multi-agent report."""
        sections = ["## 🚀 Strategic AI Architect Report\n"]

        if self.context.blueprint:
            sections.append(self.architect.format_blueprint_markdown(self.context.blueprint))
            sections.append("\n---\n")

        if self.context.patches:
            sections.append(f"### {self.coder.ICON} Applied Workspace Patches")
            for patch in self.context.patches:
                status_badge = "✅ AST-Safe" if patch.ast_safe else "⚠️ Warning"
                sections.append(f"- **{patch.file_path}** ({patch.action.upper()}) — {status_badge}: {patch.details}")
            sections.append("\n---\n")

        if self.context.verification:
            sections.append(self.verifier.format_verification_markdown(self.context.verification))
            sections.append("\n---\n")

        if custom_summary:
            sections.append(f"### 📋 Summary & Recommendations\n{custom_summary}")

        return "\n".join(sections)
