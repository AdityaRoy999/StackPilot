class ArchitectAgent:
    """
    ArchitectAgent:
    - Generates structured architectural blueprints
    - Analyzes project dependency graphs
    - Detects framework/runtime paradigms
    - Produces step-by-step execution plans
    """

    ROLE: str = "Architect Subagent"
    ICON: str = "🏛️"

    def __init__(self, name: str = "ArchitectAgent"):
        self.name = name

    def detect_paradigm(
        self,
        files: List[str],
        package_json_str: Optional[str] = None,
        dockerfile_str: Optional[str] = None,
        requirements_str: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Detect framework, runtime, and architecture paradigm from workspace layout and configs."""
        files_lower = {f.lower().replace("\\", "/") for f in files}
        
        framework = "Standard Application"
        runtime = "Unknown Runtime"
        paradigm = "Single Service Container"
        entrypoint = None
        port = None

        # Node / JS / TS ecosystem
        if "package.json" in [os.path.basename(f) for f in files_lower] or package_json_str:
            runtime = "Node.js"
            deps: Dict[str, str] = {}
            scripts: Dict[str, str] = {}
            if package_json_str:
                try:
                    pkg = json.loads(package_json_str)
                    deps.update(pkg.get("dependencies", {}))
                    deps.update(pkg.get("devDependencies", {}))
                    scripts.update(pkg.get("scripts", {}))
                except Exception:
                    pass

            if "next" in deps:
                framework = "Next.js (React)"
                paradigm = "Server-Side Rendered (SSR) Web App"
                port = 3000
                entrypoint = "npm run start" if "start" in scripts else "npm run dev"
            elif "nuxt" in deps:
                framework = "Nuxt.js (Vue)"
                paradigm = "Fullstack Vue SSR"
                port = 3000
            elif "@nestjs/core" in deps:
                framework = "NestJS"
                paradigm = "Modular Enterprise REST / GraphQL API"
                port = 3000
            elif "express" in deps:
                framework = "Express.js"
                paradigm = "RESTful HTTP Microservice"
                port = 3000 or 8080
            elif "fastify" in deps:
                framework = "Fastify"
                paradigm = "High-Throughput Node HTTP Service"
                port = 3000
            elif "react-scripts" in deps or "vite" in deps:
                framework = "Vite / React SPA"
                paradigm = "Static Single Page App with Dev Proxy"
                port = 5173 if "vite" in deps else 3000

        # Python ecosystem
        elif any(f in files_lower for f in ["requirements.txt", "pyproject.toml", "pipfile", "setup.py"]) or requirements_str:
            runtime = "Python"
            req_text = requirements_str or ""
            if "fastapi" in req_text.lower():
                framework = "FastAPI (ASGI)"
                paradigm = "Asynchronous High-Performance API"
                port = 8000
                entrypoint = "uvicorn main:app --host 0.0.0.0 --port 8000"
            elif "django" in req_text.lower():
                framework = "Django"
                paradigm = "Monolithic MVC Web Application"
                port = 8000
            elif "flask" in req_text.lower():
                framework = "Flask"
                paradigm = "Lightweight WSGI Microservice"
                port = 5000
            else:
                framework = "Python CLI / Worker"
                paradigm = "Background Processing Worker"

        # Go ecosystem
        elif any(f.endswith("go.mod") for f in files_lower):
            runtime = "Go"
            framework = "Go Module"
            paradigm = "Compiled Microservice"
            port = 8080

        # Rust ecosystem
        elif any(f.endswith("cargo.toml") for f in files_lower):
            runtime = "Rust"
            framework = "Cargo Project"
            paradigm = "High-Performance Systems Microservice"
            port = 8080

        # Docker analysis
        if dockerfile_str:
            paradigm = f"Containerized ({paradigm})"
            # Find EXPOSE
            expose_match = re.search(r"^\s*EXPOSE\s+(\d+)", dockerfile_str, re.MULTILINE | re.IGNORECASE)
            if expose_match:
                port = int(expose_match.group(1))

        return {
            "framework": framework,
            "runtime": runtime,
            "paradigm": paradigm,
            "port": port,
            "entrypoint": entrypoint,
        }

    def analyze_dependency_graph(
        self,
        package_json_str: Optional[str] = None,
        requirements_str: Optional[str] = None,
        docker_compose_str: Optional[str] = None,
    ) -> Dict[str, List[str]]:
        """Construct a lightweight dependency graph showing interconnected dependencies and tiers."""
        graph: Dict[str, List[str]] = {}

        if package_json_str:
            try:
                pkg = json.loads(package_json_str)
                prod_deps = list(pkg.get("dependencies", {}).keys())
                dev_deps = list(pkg.get("devDependencies", {}).keys())
                graph["runtime_dependencies"] = prod_deps[:25]
                if dev_deps:
                    graph["development_dependencies"] = dev_deps[:15]
            except Exception:
                pass

        if requirements_str:
            reqs: List[str] = []
            for line in requirements_str.splitlines():
                line = line.strip()
                if line and not line.startswith("#") and not line.startswith("-"):
                    name = re.split(r"[=<>!~]", line)[0].strip()
                    if name:
                        reqs.append(name)
            if reqs:
                graph["python_packages"] = reqs[:25]

        if docker_compose_str:
            services: List[str] = []
            for line in docker_compose_str.splitlines():
                m = re.match(r"^\s{2}([a-zA-Z0-9_-]+):", line)
                if m and m.group(1) not in {"version", "services", "networks", "volumes"}:
                    services.append(m.group(1))
            if services:
                graph["compose_services"] = services

        return graph

    def create_blueprint(
        self,
        goal: str,
        files: Optional[List[str]] = None,
        package_json_str: Optional[str] = None,
        dockerfile_str: Optional[str] = None,
        requirements_str: Optional[str] = None,
        logs: Optional[str] = None,
    ) -> ArchitectBlueprint:
        """Synthesize a complete, structured Architectural Blueprint."""
        file_list = files or []
        paradigm_info = self.detect_paradigm(
            file_list,
            package_json_str=package_json_str,
            dockerfile_str=dockerfile_str,
            requirements_str=requirements_str,
        )
        dep_graph = self.analyze_dependency_graph(
            package_json_str=package_json_str,
            requirements_str=requirements_str,
        )

        steps: List[str] = [
            f"1. Workspace Inspection: Verify files in {paradigm_info['framework']} codebase.",
            "2. Dependency Graph Resolution: Validate integrity of runtime packages and build configurations.",
            "3. Surgical Code Modifications: Apply AST-safe patches to resolve configuration or syntax flaws.",
            "4. Workspace Rebuild: Queue container rebuild reflecting modified files.",
            "5. Runtime & Network Verification: Poll deployment readiness and probe health endpoints.",
        ]

        risks: List[str] = []
        if not dockerfile_str and "dockerfile" not in [os.path.basename(f).lower() for f in file_list]:
            risks.append("No explicit Dockerfile found; relies on automated builder detection.")
        if paradigm_info.get("port") is None:
            risks.append("Container listening port not explicitly declared in source configuration.")
        if logs and any(err in logs.lower() for err in ["syntaxerror", "cannot find module", "crashloop"]):
            risks.append("Pre-existing runtime crash detected in deployment logs.")

        files_to_modify: List[str] = []
        if package_json_str and "package.json" in [os.path.basename(f) for f in file_list]:
            files_to_modify.append("package.json")
        elif requirements_str and "requirements.txt" in [os.path.basename(f) for f in file_list]:
            files_to_modify.append("requirements.txt")

        return ArchitectBlueprint(
            goal=goal,
            framework=paradigm_info["framework"],
            runtime_paradigm=paradigm_info["paradigm"],
            entrypoint=paradigm_info.get("entrypoint"),
            port=paradigm_info.get("port"),
            dependency_graph=dep_graph,
            execution_steps=steps,
            files_to_modify=files_to_modify,
            files_to_create=[],
            risk_assessment=risks,
            rationale=f"Architected plan for {paradigm_info['framework']} under {paradigm_info['paradigm']} paradigm.",
        )

    def format_blueprint_markdown(self, blueprint: ArchitectBlueprint) -> str:
        """Render markdown representation of blueprint."""
        lines = [
            f"### {self.ICON} Architectural Blueprint",
            f"- **Framework**: `{blueprint.framework}`",
            f"- **Runtime Paradigm**: `{blueprint.runtime_paradigm}`",
        ]
        if blueprint.port:
            lines.append(f"- **Target Port**: `{blueprint.port}`")
        if blueprint.entrypoint:
            lines.append(f"- **Entrypoint**: `{blueprint.entrypoint}`")
        
        lines.append("\n**Execution Plan**:")
        for step in blueprint.execution_steps:
            lines.append(f"- {step}")
            
        if blueprint.risk_assessment:
            lines.append("\n**Risk Assessment**:")
            for risk in blueprint.risk_assessment:
                lines.append(f"- ⚠️ {risk}")

        return "\n".join(lines)


