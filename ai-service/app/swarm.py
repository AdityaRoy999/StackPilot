class VerifierAgent:
    """
    VerifierAgent:
    - Validates workspace build integrity
    - Verifies container readiness
    - Checks logs for fatal errors and crash patterns
    - Probes live network endpoints
    """

    ROLE: str = "Verifier Subagent"
    ICON: str = "🔍"

    ERROR_SIGNATURES = [
        re.compile(r"SyntaxError:\s*.+", re.IGNORECASE),
        re.compile(r"Cannot find module\s*['\"].+?['\"]", re.IGNORECASE),
        re.compile(r"ModuleNotFoundError:\s*No module named\s*['\"].+?['\"]", re.IGNORECASE),
        re.compile(r"Traceback \(most recent call last\):", re.IGNORECASE),
        re.compile(r"npm ERR!\s*.+", re.IGNORECASE),
        re.compile(r"yarn error\s*.+", re.IGNORECASE),
        re.compile(r"EADDRINUSE|address already in use", re.IGNORECASE),
        re.compile(r"ECONNREFUSED|connection refused", re.IGNORECASE),
        re.compile(r"CrashLoopBackOff", re.IGNORECASE),
        re.compile(r"OutOfMemoryError|OOMKilled", re.IGNORECASE),
        re.compile(r"Segmentation fault", re.IGNORECASE),
        re.compile(r"panic:\s*.+", re.IGNORECASE),
        re.compile(r"FATAL:\s*.+", re.IGNORECASE),
    ]

    def __init__(self, name: str = "VerifierAgent"):
        self.name = name

    def check_logs(self, logs: str) -> List[str]:
        """Scan logs for critical error patterns and crash signatures."""
        found_errors: List[str] = []
        if not logs:
            return found_errors

        for sig in self.ERROR_SIGNATURES:
            for match in sig.finditer(logs):
                msg = match.group(0).strip()
                if msg and msg not in found_errors:
                    found_errors.append(msg)
                    if len(found_errors) >= 10:
                        break
            if len(found_errors) >= 10:
                break

        return found_errors

    async def probe_endpoint(self, url: str, timeout: float = 6.0) -> Dict[str, Any]:
        """Probe live network endpoint for responsiveness and health status."""
        result: Dict[str, Any] = {
            "url": url,
            "status_code": None,
            "healthy": False,
            "latency_ms": 0,
            "error": None,
        }
        start = time.perf_counter()
        try:
            async with httpx.AsyncClient(timeout=timeout, follow_redirects=True) as client:
                resp = await client.get(url)
                result["latency_ms"] = int((time.perf_counter() - start) * 1000)
                result["status_code"] = resp.status_code
                result["healthy"] = 200 <= resp.status_code < 400
        except Exception as exc:
            result["latency_ms"] = int((time.perf_counter() - start) * 1000)
            result["error"] = str(exc)
            result["healthy"] = False

        return result

    def validate_build_integrity(
        self,
        deployment_status: Dict[str, Any],
        logs: str = "",
        tested_endpoints: Optional[List[Dict[str, Any]]] = None,
    ) -> VerificationReport:
        """Synthesize overall build and runtime verification report."""
        status_val = str(deployment_status.get("status", "")).lower()
        build_ok = status_val in {"running", "ready", "active", "built", "succeeded", "success"}
        container_ready = status_val in {"running", "ready", "active"}

        errors = self.check_logs(logs)
        endpoints = tested_endpoints or []
        endpoints_live = bool(endpoints) and all(ep.get("healthy", False) for ep in endpoints)

        overall_status: Literal["passed", "failed", "warning"] = "passed"
        if status_val in {"failed", "error", "crashloop"} or errors or (endpoints and not endpoints_live):
            overall_status = "failed"
        elif not build_ok or not container_ready or not endpoints or deployment_status.get('verified') is not True:
            overall_status = "warning"

        summary_parts = []
        if container_ready:
            summary_parts.append("Container is active and in running state.")
        else:
            summary_parts.append(f"Container status is '{status_val}'.")

        if errors:
            summary_parts.append(f"{len(errors)} error signature(s) detected in logs.")
        else:
            summary_parts.append("No crash signatures detected in logs.")

        if endpoints:
            live_count = sum(1 for e in endpoints if e.get("healthy"))
            summary_parts.append(f"{live_count}/{len(endpoints)} endpoints responsive.")

        return VerificationReport(
            status=overall_status,
            build_integrity=build_ok,
            container_readiness=container_ready,
            network_endpoints_live=endpoints_live,
            errors_found=errors,
            tested_endpoints=endpoints,
            summary=" ".join(summary_parts),
        )

    def format_verification_markdown(self, report: VerificationReport) -> str:
        """Format verification report into clean markdown."""
        icon = "✅" if report.status == "passed" else ("⚠️" if report.status == "warning" else "❌")
        lines = [
            f"### {self.ICON} Verification Report ({icon} {report.status.upper()})",
            f"- **Build Integrity**: {'Pass' if report.build_integrity else 'Fail'}",
            f"- **Container Readiness**: {'Ready' if report.container_readiness else 'Not Ready'}",
            f"- **Network Endpoints**: {'Live' if report.network_endpoints_live else 'Unreachable'}",
            f"- **Summary**: {report.summary}",
        ]
        if report.errors_found:
            lines.append("\n**Detected Log Anomalies**:")
            for err in report.errors_found[:5]:
                lines.append(f"- `{err}`")
        return "\n".join(lines)


