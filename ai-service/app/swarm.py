class CoderAgent:
    """
    CoderAgent:
    - Performs surgical, AST-safe file edits
    - Verifies syntax integrity across Python, JSON, JS/TS
    - Creates new files with complete implementations
    """

    ROLE: str = "Coder Subagent"
    ICON: str = "⚡"

    def __init__(self, name: str = "CoderAgent"):
        self.name = name

    def verify_syntax(self, file_path: str, code: str) -> Tuple[bool, Optional[str]]:
        """Verify syntax integrity of proposed code content."""
        ext = os.path.splitext(file_path)[1].lower()

        # Python AST verification
        if ext == ".py":
            try:
                ast.parse(code, filename=file_path)
                return True, None
            except SyntaxError as exc:
                return False, f"Python SyntaxError at line {exc.lineno}: {exc.msg}"
            except Exception as exc:
                return False, f"Python AST parse error: {str(exc)}"

        # JSON verification
        if ext in {".json", ".jsonc"}:
            try:
                json.loads(code)
                return True, None
            except json.JSONDecodeError as exc:
                return False, f"JSON syntax error at line {exc.lineno}, col {exc.colno}: {exc.msg}"

        # JavaScript / TypeScript balanced delimiter verification
        if ext in {".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs"}:
            balanced, msg = self._check_delimiters(code)
            if not balanced:
                return False, f"JS/TS delimiter mismatch: {msg}"
            return True, None

        # General file - basic sanity check
        return True, None

    def _check_delimiters(self, text: str) -> Tuple[bool, Optional[str]]:
        """Check matching braces, brackets, parentheses, and quotes in JS/TS text."""
        stack: List[Tuple[str, int]] = []
        matching = {')': '(', '}': '{', ']': '['}
        line_num = 1

        in_line_comment = False
        in_block_comment = False
        in_string: Optional[str] = None
        escape = False

        i = 0
        n = len(text)
        while i < n:
            ch = text[i]
            if ch == '\n':
                line_num += 1
                in_line_comment = False

            if in_line_comment:
                i += 1
                continue

            if in_block_comment:
                if ch == '*' and i + 1 < n and text[i + 1] == '/':
                    in_block_comment = False
                    i += 2
                    continue
                i += 1
                continue

            if escape:
                escape = False
                i += 1
                continue

            if ch == '\\':
                escape = True
                i += 1
                continue

            if in_string:
                if ch == in_string:
                    in_string = None
                i += 1
                continue

            # Comment starts
            if ch == '/' and i + 1 < n:
                if text[i + 1] == '/':
                    in_line_comment = True
                    i += 2
                    continue
                elif text[i + 1] == '*':
                    in_block_comment = True
                    i += 2
                    continue

            # String starts
            if ch in {'"', "'", '`'}:
                in_string = ch
                i += 1
                continue

            if ch in matching.values():
                stack.append((ch, line_num))
            elif ch in matching:
                expected = matching[ch]
                if not stack:
                    return False, f"Unmatched '{ch}' at line {line_num}"
                last_open, open_line = stack.pop()
                if last_open != expected:
                    return False, f"Mismatched closing '{ch}' at line {line_num} (opened '{last_open}' at line {open_line})"

            i += 1

        if stack:
            unclosed, open_line = stack[-1]
            return False, f"Unclosed '{unclosed}' from line {open_line}"

        return True, None

    def is_ast_safe_edit(
        self,
        original_content: str,
        target: str,
        replacement: str,
        file_path: str = "",
    ) -> Tuple[bool, str]:
        """Validate if a find-and-replace edit preserves AST and syntax validity."""
        if target not in original_content:
            return False, f"Target string not found in {file_path or 'file'}."

        occurrences = original_content.count(target)
        if occurrences > 1:
            return False, f"Target string is ambiguous ({occurrences} occurrences found). Provide unique context."

        # Perform trial edit
        modified_content = original_content.replace(target, replacement, 1)

        # Verify syntax on candidate result
        is_valid, err = self.verify_syntax(file_path, modified_content)
        if not is_valid:
            return False, f"Edit introduces syntax invalidity: {err}"

        return True, "Edit is AST-safe and syntactically valid."

    def prepare_patch(
        self,
        file_path: str,
        action: Literal["edit", "write"],
        target: Optional[str] = None,
        replacement: Optional[str] = None,
        content: Optional[str] = None,
        original_content: Optional[str] = None,
    ) -> CodePatch:
        """Create a validated CodePatch object."""
        if action == "edit":
            if not target or replacement is None:
                return CodePatch(
                    file_path=file_path,
                    action="edit",
                    syntax_valid=False,
                    ast_safe=False,
                    error_message="Target and replacement are required for surgical edit.",
                )
            if original_content is not None:
                is_safe, msg = self.is_ast_safe_edit(original_content, target, replacement, file_path)
                return CodePatch(
                    file_path=file_path,
                    action="edit",
                    target=target,
                    replacement=replacement,
                    syntax_valid=is_safe,
                    ast_safe=is_safe,
                    details=msg,
                    error_message=None if is_safe else msg,
                )
            return CodePatch(
                file_path=file_path,
                action="edit",
                target=target,
                replacement=replacement,
                syntax_valid=True,
                ast_safe=True,
                details="Prepared surgical edit.",
            )

        elif action == "write":
            if content is None:
                return CodePatch(
                    file_path=file_path,
                    action="write",
                    syntax_valid=False,
                    ast_safe=False,
                    error_message="Content is required for write patch.",
                )
            is_valid, err = self.verify_syntax(file_path, content)
            return CodePatch(
                file_path=file_path,
                action="write",
                content=content,
                syntax_valid=is_valid,
                ast_safe=is_valid,
                details="Complete file implementation ready.",
                error_message=err,
            )

        return CodePatch(file_path=file_path, action="verify", details="No-op verify patch.")

    async def execute_patch(
        self,
        patch: CodePatch,
        user_id: str,
        project_id: Optional[str] = None,
        deployment_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Execute the validated patch against the backend workspace tool."""
        if not patch.syntax_valid or not patch.ast_safe:
            return {
                "status": "error",
                "error": f"Refusing to apply invalid patch: {patch.error_message or 'AST syntax violation'}",
            }

        args: Dict[str, Any] = {"file_path": patch.file_path}
        if project_id:
            args["project_id"] = project_id
        if deployment_id:
            args["deployment_id"] = deployment_id

        if patch.action == "edit" and patch.target and patch.replacement is not None:
            args["target"] = patch.target
            args["replacement"] = patch.replacement
            return await execute_tool_call("workspace_edit_file", args, user_id)
        elif patch.action == "write" and patch.content is not None:
            args["content"] = patch.content
            return await execute_tool_call("workspace_write_file", args, user_id)

        return {"status": "error", "error": f"Unsupported patch action: {patch.action}"}


