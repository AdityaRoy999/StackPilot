"""Translate a declared Vite production deployment, including hosted API rewrites.

Discovery never executes repository code. Install/build commands execute only
inside the isolated build image. An explicit StackPilot contract stays authoritative.
"""
import json
from pathlib import Path, PurePosixPath
import re
import shlex
import shutil
import subprocess
from urllib.parse import urlsplit


def document(root, name):
    path = root/name
    if path.is_symlink() or not path.is_file() or path.stat().st_size > 1024*1024:
        return None
    return json.loads(path.read_text(encoding='utf-8-sig'))


def relative(root, value):
    if not isinstance(value, str) or not value or any(c in value for c in '\\\0\r\n:'):
        raise ValueError('Frontend output must be a repository-relative directory')
    path = PurePosixPath(value)
    if path.is_absolute() or '..' in path.parts or path == PurePosixPath('.'):
        raise ValueError('Frontend output escapes its build directory')
    target = root.joinpath(*path.parts)
    if not target.resolve().is_relative_to(root) or any(p.is_symlink() for p in [target,*target.parents] if p.is_relative_to(root)):
        raise ValueError('Frontend output must not use symlinks')
    return path.as_posix()


def command(value):
    if not isinstance(value, str) or not 1 <= len(value) <= 4096:
        raise ValueError('Production command needs bounded executable arguments')
    argv = shlex.split(value)
    if not argv or argv[0] not in {'npm','pnpm','yarn','bun'} or any(re.search(r'[;&|<>`\n\r\0]|\$\(', a) for a in argv):
        raise ValueError('Production command requires explicit package-manager argv; shell expressions need a declared Dockerfile')
    return argv


def infer(root, context=None):
    root = Path(root).resolve()
    selected=(context or {}).get('deployment',{})
    if str(selected.get('environment_name','')).lower() in {'dev','development','local','test','testing'} and any(
            (root/name).is_file() for name in ('compose.yml','compose.yaml','docker-compose.yml','docker-compose.yaml')):
        return None
    existing_dockerfile = root/'Dockerfile'
    if existing_dockerfile.is_file() and not any(marker in existing_dockerfile.read_text(encoding='utf-8') for marker in
            ('# Generated by StackPilot Linux recipes', '# Generated by StackPilot hosted frontend recipe')):
        return None
    config = document(root, 'vercel.json')
    package = document(root, 'package.json')
    if not isinstance(config, dict) or config.get('framework') != 'vite' or not isinstance(package, dict):
        return None
    if not config.get('outputDirectory') or not config.get('buildCommand'):
        return None
    output = relative(root, config['outputDirectory'])
    component = str(PurePosixPath(output).parent)
    manifest = document(root, component+'/package.json') if component != '.' else package
    if not isinstance(manifest, dict) or 'vite' not in {**manifest.get('dependencies', {}),**manifest.get('devDependencies', {})}:
        return None
    # Explicit HTTPS rewrites establish that this production frontend depends
    # on an already hosted service. A development Compose file is not that target.
    proxies = []
    for rewrite in config.get('rewrites', []):
        if not isinstance(rewrite, dict):
            raise ValueError('Production rewrites must be objects')
        source, destination = rewrite.get('source', ''), rewrite.get('destination', '')
        if not isinstance(destination, str) or not destination.startswith(('http:', 'https:')):
            continue
        if not isinstance(source, str) or not re.fullmatch(r'/[A-Za-z0-9_/-]+/:path\*', source):
            raise ValueError('Hosted API rewrite needs a literal path prefix and :path* suffix')
        parts = urlsplit(destination.removesuffix(':path*'))
        if (parts.scheme != 'https' or not parts.hostname or parts.username or parts.password or parts.query or parts.fragment
                or not re.fullmatch(r'[A-Za-z0-9.-]+(?::[0-9]{1,5})?', parts.netloc) or parts.hostname in {'localhost','127.0.0.1'}
                or not re.fullmatch(r'/[A-Za-z0-9_./-]*', parts.path) or '..' in parts.path.split('/')):
            raise ValueError('Hosted API rewrites require a public HTTPS origin without credentials')
        if parts.port is not None and not 1 <= parts.port <= 65535:
            raise ValueError('Hosted API port must be between 1 and 65535')
        if not destination.endswith('/:path*'):
            raise ValueError('Hosted API rewrite must preserve the complete request suffix')
        proxies.append({'prefix': source[:-len(':path*')], 'upstream': destination[:-len(':path*')]})
    if not proxies:
        return None
    if len(proxies) > 16 or len({p['prefix'] for p in proxies}) != len(proxies):
        raise ValueError('Hosted API rewrite prefixes must be unique and bounded')
    install = command(config.get('installCommand', 'npm ci' if (root/'package-lock.json').is_file() else 'npm install'))
    build = command(config['buildCommand'])
    try:
        from .repository_toolchains import verification_profile
    except ImportError:
        from repository_toolchains import verification_profile
    profile = verification_profile(root)
    if profile.get('kind') != 'node' or profile['issues'] or not profile.get('image'):
        raise ValueError('Hosted frontend requires the repository Node toolchain')
    checks=[]
    render = root/'render.yaml'
    if render.is_file() and not render.is_symlink() and render.stat().st_size < 1024*1024 and len(proxies)==1:
        try:
            import yaml
        except ImportError:
            service = None  # Isolated Node builds need no YAML dependency.
        else:
            service = yaml.safe_load(render.read_text(encoding='utf-8'))
        services = service.get('services',[]) if isinstance(service,dict) else []
        if len(services)==1 and isinstance(services[0],dict):
            health=services[0].get('healthCheckPath')
            if isinstance(health,str) and re.fullmatch(r'/[A-Za-z0-9_/-]+',health):
                checks=[{'path':proxies[0]['prefix'].rstrip('/')+health,'statuses':[200]}]
    return {'version': 1, 'workload': 'web', 'deployment_mode': 'dockerfile', 'port': 3000,
            'health': {'path': '/', 'statuses': [200]},
            'tests': [build], 'tests_required': True, 'checks':checks,
            'static_frontend': {'config': 'vercel.json', 'root': component, 'output': output,
                'image': profile['image'], 'install': install, 'build': build, 'proxies': proxies}}


def nginx(config):
    lines = ['pid /tmp/nginx.pid;', 'events {}', 'http {', 'include /etc/nginx/mime.types;',
             'default_type application/octet-stream;', 'client_body_temp_path /tmp/client_temp;',
             'proxy_temp_path /tmp/proxy_temp;', 'fastcgi_temp_path /tmp/fastcgi_temp;',
             'uwsgi_temp_path /tmp/uwsgi_temp;', 'scgi_temp_path /tmp/scgi_temp;',
             'server { listen 3000; root /usr/share/nginx/html; index index.html;']
    for proxy in config['static_frontend']['proxies']:
        parts = urlsplit(proxy['upstream'])
        lines.extend(['location '+proxy['prefix']+' {', 'proxy_pass '+proxy['upstream']+';',
            'proxy_ssl_server_name on;', 'proxy_ssl_verify on;', 'proxy_ssl_verify_depth 4;',
            'proxy_ssl_trusted_certificate /etc/ssl/certs/ca-certificates.crt;',
            'proxy_set_header Host '+parts.netloc+';', 'proxy_http_version 1.1;',
            'proxy_set_header Connection "";', 'proxy_buffering off;', 'proxy_read_timeout 300s;', '}'])
    lines.extend(['location / { try_files $uri $uri/ /index.html; }', '}', '}'])
    return '\n'.join(lines)+'\n'


def dockerfile(config):
    value = config['static_frontend']
    return ('# Generated by StackPilot hosted frontend recipe\nFROM '+value['image']+' AS builder\n'
        'RUN apt-get update && apt-get install -y --no-install-recommends python3 ca-certificates && rm -rf /var/lib/apt/lists/*\n'
        'WORKDIR /source\nCOPY . .\nRUN python3 .stackpilot-runtime/hosted_frontend.py build\n'
        'FROM nginx:alpine\nCOPY --from=builder /stackpilot-output/ /usr/share/nginx/html/\n'
        'COPY .stackpilot-runtime/hosted-nginx.conf /etc/nginx/nginx.conf\n'
        'COPY --from=builder /source/.stackpilot-tests.json /stackpilot-evidence/tests.json\n'
        'USER 65534:65534\nEXPOSE 3000\nCMD ["nginx", "-g", "daemon off;"]\n')


def build(root):
    root = Path(root).resolve()
    config = json.loads((root/'stackpilot.json').read_text())
    # Re-derive from the original production inputs rather than trusting a
    # forged static_frontend object to inject nginx directives or source paths.
    expected = infer(root)
    if not expected or config.get('static_frontend') != expected['static_frontend']:
        raise ValueError('Hosted frontend recipe no longer matches its production inputs')
    value = expected['static_frontend']
    public = root/'.env.production.local'
    component = root/value['root']
    if component != root and public.is_file():
        target = component/'.env.production.local'
        if target.is_symlink():raise ValueError('Public frontend environment must not use symlinks')
        lines = public.read_text(encoding='utf-8').splitlines()
        if any(line and not re.match(r'^(VITE_|NEXT_PUBLIC_|REACT_APP_|PUBLIC_)[A-Za-z0-9_]*=', line) for line in lines):
            raise ValueError('Only explicitly public variables may enter a frontend build')
        # Project/environment overrides prepared by the broker are authoritative.
        target.write_text(public.read_text(encoding='utf-8'), encoding='utf-8')
    subprocess.run(value['install'], cwd=root, check=True, timeout=1200)
    from repository_tests import test
    test(root)  # The declared production build must pass, with its real exit code.
    output = root/value['output']
    if not (output/'index.html').is_file() or any(p.is_symlink() for p in [output,*output.rglob('*')]):
        raise ValueError('Frontend build must produce real compiled HTML without symlinks')
    if any(p.name.startswith('.env') for p in output.rglob('*')):
        raise ValueError('Frontend output must not export environment files')
    shutil.copytree(output, '/stackpilot-output', dirs_exist_ok=True)


if __name__ == '__main__':
    import sys
    if sys.argv[1:] != ['build']:raise SystemExit('Expected isolated build operation')
    build(Path.cwd())
