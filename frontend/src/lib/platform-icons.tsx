"use client";
import { forwardRef } from "react";
import type { LucideIcon } from "lucide-react";
import { AppIcon, PLATFORM_ICON_IDS } from "./custom-icons";
import { PLATFORM_LUCIDE_ICONS } from "./platform-icon-map";
export type { LucideIcon, LucideProps } from "lucide-react";

function configurable(name: keyof typeof PLATFORM_LUCIDE_ICONS): LucideIcon {
  const Original = PLATFORM_LUCIDE_ICONS[name];
  const Icon = forwardRef<SVGSVGElement, React.ComponentProps<LucideIcon>>((props, ref) => (
    <AppIcon name={PLATFORM_ICON_IDS[name]} fallback={Original} strokeWidth={1.75} {...props} ref={ref} />
  ));
  Icon.displayName = `Platform${name}`;
  return Object.assign(Icon, { __stackpilotRawIcon: Original });
}
